#!/bin/sh
set -eu

db_host="${PGHOST:-db}"
db_user="${PGUSER:-rideforge}"
db_name="${PGDATABASE:-rideforge}"
migrations_dir="${RIDEFORGE_MIGRATIONS_DIR:-/migrations}"
schema_file="${RIDEFORGE_SCHEMA_FILE:-}"

psql_db() {
  if [ -n "${DATABASE_URL:-}" ]; then
    psql "$DATABASE_URL" "$@"
  else
    psql -h "$db_host" -U "$db_user" -d "$db_name" "$@"
  fi
}

migration_table="$(psql_db -tAc "SELECT to_regclass('public.schema_migrations')")"
accounts_table="$(psql_db -tAc "SELECT to_regclass('public.accounts')")"

if [ "$accounts_table" = "accounts" ]; then
  if [ "$migration_table" != "schema_migrations" ] ||
     ! psql_db -tAc "SELECT 1 FROM schema_migrations WHERE version = '001_initial_schema'" | grep -Fqx 1; then
    echo "Existing schema is missing the recorded initial migration; refusing unsafe automatic migration. Back up the database and baseline schema_migrations deliberately." >&2
    exit 1
  fi
fi

if [ -n "$schema_file" ]; then
  set -- "$schema_file"
elif [ -d "$migrations_dir" ]; then
  set -- "$migrations_dir"/*.sql
else
  echo "Migration directory not found: $migrations_dir" >&2
  exit 1
fi

if [ "$#" -eq 0 ] || [ ! -f "$1" ]; then
  echo "No SQL migration files found." >&2
  exit 1
fi

for file do
  [ -f "$file" ] || continue
  version="$(basename "$file" .sql)"
  if [ "$migration_table" = "schema_migrations" ] &&
     psql_db -tAc "SELECT 1 FROM schema_migrations WHERE version = '$version'" | grep -Fqx 1; then
    echo "Migration $version already applied"
    continue
  fi
  echo "Applying migration $version"
  psql_db -v ON_ERROR_STOP=1 -f "$file"
  migration_table="schema_migrations"
done

# Configure the private runtime role separately from the migration owner. The
# password is generated by the operator and passed only through the environment;
# restrict its alphabet so psql's quoted variable substitution remains safe.
if [ -n "${RIDEFORGE_APP_PASSWORD:-}" ]; then
  case "$RIDEFORGE_APP_PASSWORD" in
    *[!A-Za-z0-9_-]*)
      echo "RIDEFORGE_APP_PASSWORD may contain only letters, digits, underscore and hyphen." >&2
      exit 1
      ;;
  esac
  if [ "${#RIDEFORGE_APP_PASSWORD}" -lt 32 ]; then
    echo "RIDEFORGE_APP_PASSWORD must contain at least 32 characters." >&2
    exit 1
  fi
  # The alphabet is restricted above, so embedding this value in the SQL
  # literal is safe. psql does not interpolate :'variables' inside -c strings.
  psql_db -v ON_ERROR_STOP=1 \
    -c "ALTER ROLE rideforge_app PASSWORD '$RIDEFORGE_APP_PASSWORD'"
fi
